export const SEGMENT_IDS = SEGMENTS.map((s) => s.id);

export function segmentHref(segmentId: string) {
  return `/services/${segmentId}`;
}

export function childHref(segmentId: string, childId: string) {
  return `/services/${segmentId}/${childId}`;
}

export function getSegmentById(id: string) {
  return SEGMENTS.find((s) => s.id === id);
}

export function getChildById(segmentId: string, childId: string) {
  const segment = getSegmentById(segmentId);
  return segment?.children?.find((c) => c.id === childId);
}

export function getAllChildParams() {
  const params: { segment: string; child: string }[] = [];
  for (const segment of SEGMENTS) {
    for (const child of segment.children ?? []) {
      params.push({ segment: segment.id, child: child.id });
    }
  }
  return params;
}

export function segmentWheelLabel(segment: EcosystemSegment) {
  return segment.menuLabel ?? segment.label;
}

export function childFlyoutLabel(child: EcosystemChild) {
  return child.menuLabel ?? child.label;
}

export function childPageDescription(
  segmentLabel: string,
  child: EcosystemChild,
): string {
  if (child.description) return child.description;
  return `${child.label} — بخشی از ${segmentLabel} در اکوسیستم پیشران.`;
}
